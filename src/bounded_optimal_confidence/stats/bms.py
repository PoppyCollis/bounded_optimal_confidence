"""Random-effects Bayesian model selection for group studies (Stephan et al. 2009; Rigoux et al. 2014).

Each subject's data are treated as generated by one of K models, drawn from unknown population frequencies r with a
Dirichlet prior. Given a K x N matrix L of log model evidences (one per model and subject), a variational scheme
fits a Dirichlet posterior on r with counts alpha. From it:

    frequency   E[r_k] = alpha_k / sum(alpha): the expected share of the population best described by model k
    XP          exceedance probability p(r_k > r_j for all j != k): the probability that model k is the most common
    BOR         Bayesian omnibus risk: the posterior probability of the null "all models equally common"
    PXP         protected exceedance probability XP (1 - BOR) + BOR / K (Rigoux et al. 2014, eq. 7): the one to report

The equation numbers below refer to the appendix of Rigoux et al. (2014). The arithmetic follows the `groupBMC`
package (Sichao Yang, MIT licence, (c) 2020 cpilab; a port of VBA_groupBMC from the VBA toolbox) operation for
operation, so the two give identical numbers; `tests/test_bms.py` checks this. Two things are done differently:

- The null's log evidence is exact, sum_n log[sum_k null_k exp(L_kn)] (Rigoux et al. eq. 17 with the null
  frequencies plugged in). groupBMC's `F0` takes log(alpha_0) as the null frequencies, which is only right for its
  default prior alpha_0 = 1 / K; with the flat prior alpha_0 = 1 used here it returns BOR = 1.
- The prior is a parameter. `bms` uses the flat Dirichlet alpha_0 = 1 per model, as spm_BMS and both papers do.
  `family_bms` puts the prior on families (Penny et al. 2010).
"""
from dataclasses import dataclass
from math import exp, log

import numpy as np
from scipy import integrate
from scipy.special import digamma, expit, gammainc, gammaln, logsumexp, softmax

MAX_ITER = 500          # variational iterations (groupBMC's defaults are 32 and 1e-4)
TOLERANCE = 1e-8        # convergence: change in the free energy
EPS = np.finfo(float).eps


@dataclass(frozen=True)
class BMSResult:
    alpha: np.ndarray       # posterior Dirichlet counts, one per model (or per family)
    frequency: np.ndarray   # expected population frequency of each model
    xp: np.ndarray          # exceedance probability
    pxp: np.ndarray         # protected exceedance probability
    bor: float              # Bayesian omnibus risk


def variational_fit(L, alpha_0):
    """Fit the Dirichlet posterior on the model frequencies (eq. A21), iterated to convergence of the free energy.

    L is K models x N subjects, alpha_0 the K prior counts. Returns (alpha, z, F): the posterior counts, the
    K x N posterior probabilities that each subject's data come from each model, and the final free energy F1.
    """
    L = np.asarray(L, dtype=float)
    alpha_0 = np.asarray(alpha_0, dtype=float)[:, None]
    alpha = alpha_0.copy()
    F = []
    for _ in range(MAX_ITER):
        z = softmax(L + digamma(alpha), axis=0)                 # subject attributions (A21, line 2)
        alpha = alpha_0 + z.sum(axis=1, keepdims=True)          # counts: prior + attributed subjects (A21, line 1)
        F.append(free_energy(L, alpha_0, alpha, z))
        if len(F) > 1 and abs(F[-1] - F[-2]) < TOLERANCE:
            break
    else:
        raise RuntimeError(f"the variational fit did not converge in {MAX_ITER} iterations")
    return alpha.ravel(), z, F[-1]


def free_energy(L, alpha_0, alpha, z):
    """The variational free energy F1 of the posterior (alpha, z): a lower bound on the log evidence (eq. A20)."""
    E_log_r = digamma(alpha) - digamma(alpha.sum())
    E_log_joint = (z * (L + E_log_r)).sum() + ((alpha_0 - 1) * E_log_r).sum()
    E_log_joint += gammaln(alpha_0.sum()) - gammaln(alpha_0).sum()
    entropy_z = -(z * np.log(z + EPS)).sum()
    entropy_alpha = gammaln(alpha).sum() - gammaln(alpha.sum()) - ((alpha - 1) * E_log_r).sum()
    return E_log_joint + entropy_z + entropy_alpha


def null_log_evidence(L, null):
    """Exact log evidence of the null hypothesis that the model frequencies are fixed at `null` (K values summing
    to 1): each subject's data are then a mixture of the models with those weights."""
    return logsumexp(L + np.log(null)[:, None], axis=0).sum()


def omnibus_risk(L, null, F1):
    """BOR = p(H0 | data) with equal prior odds: the null's log evidence against the fitted model's free energy."""
    return float(expit(null_log_evidence(L, null) - F1))


def exceedance_probability(alpha):
    """XP of a Dirichlet(alpha): the probability that each component is the largest.

    Written as a Gamma representation and integrated numerically (Soch & Allefeld 2016): r_k is the largest when the
    Gamma(alpha_k) variate behind it exceeds the other K - 1, so XP_k = int_0^inf Gamma_k(x) prod_{j != k} P(G_j < x) dx.
    """
    alpha = np.asarray(alpha, dtype=float)
    n = len(alpha)
    log_norm = [gammaln(alpha[i]) for i in range(n)]

    def integrand(x, i):                                        # scalar math, as in groupBMC
        p = 1
        for j in range(n):
            if i != j:
                p *= gammainc(alpha[j], x)                      # regularised lower incomplete gamma: P(G_j < x)
        return p * exp((alpha[i] - 1) * log(x) - x - log_norm[i])

    xp = np.array([integrate.quad(lambda x: integrand(x, i), 0, np.inf)[0] for i in range(n)])
    return xp / xp.sum()


def _result(alpha, bor):
    xp = exceedance_probability(alpha)
    return BMSResult(alpha, alpha / alpha.sum(), xp, xp * (1 - bor) + bor / len(alpha), bor)


def bms(L):
    """Model-level BMS on a K models x N subjects log-evidence matrix.

    Prior: flat Dirichlet, alpha_0 = 1 per model. Null: every model equally common (frequencies 1 / K).
    """
    K = L.shape[0]
    alpha, _z, F1 = variational_fit(L, np.ones(K))
    return _result(alpha, omnibus_risk(L, np.full(K, 1 / K), F1))


def family_bms(L, sizes, prior="penny"):
    """Family-level BMS: the models are grouped into families and the question is which family is the most common.

    The rows of L are ordered by family, `sizes` giving the number of models in each. The counts of a family are the
    summed counts of its members (Penny et al. 2010). Two priors on the models:

        "penny"     1 per family, split equally among its members, so a family is not favoured for having more
                    members (Penny et al. 2010)
        "groupbmc"  the groupBMC package's default for partitions, 1 / (n_families x size) per model: also flat over
                    families, but the counts sum to 1 instead of to n_families

    Null: every family equally common, split equally inside.
    """
    penny = np.concatenate([np.full(n, 1 / n) for n in sizes])
    null = penny / len(sizes)
    alpha_0 = {"penny": penny, "groupbmc": null}[prior]
    alpha, _z, F1 = variational_fit(L, alpha_0)
    family = np.repeat(np.arange(len(sizes)), sizes)            # family index of each model
    return _result(np.bincount(family, weights=alpha), omnibus_risk(L, null, F1))
